const assert = require('assert');
const { assembleToObject } = require('../out/linker');
const object = assembleToObject('main:\n  jmp external, r14\n');
assert(object.symbols.some(symbol => symbol.name === 'external' && !symbol.defined));
assert.strictEqual(object.relocations[0].symbol, 'external');
const normalized = assembleToObject('start:\n\n  jmp helper, r14\n  bz r4, r0 + done\nhelper:\n  jmp r14\ndone:\n');
assert.strictEqual(normalized.sections[0].size, 12);
assert.strictEqual(normalized.symbols.find(symbol => symbol.name === 'start').offset, 0);
assert.strictEqual(normalized.symbols.find(symbol => symbol.name === 'helper').offset, 8);
assert.strictEqual(normalized.symbols.find(symbol => symbol.name === 'done').offset, 12);
assert.strictEqual(normalized.relocations.length, 2);
assert.strictEqual(normalized.relocations[0].offset, 0);
assert.strictEqual(normalized.relocations[0].kind, 'CALL16');
assert.strictEqual(normalized.relocations[1].kind, 'BRANCH16');
assert.strictEqual(normalized.relocations[1].offset, 4);
assert.strictEqual(normalized.relocations[0].debug.line, 3);
assert.strictEqual(normalized.relocations[0].debug.column, 5);
const entry = assembleToObject('.entry start\nstart:\n  jmp r14\n');
assert.strictEqual(entry.sections[0].size, 4);
assert.strictEqual(entry.symbols.find(symbol => symbol.name === 'start').offset, 0);
assert.strictEqual(entry.relocations.length, 0);
const comments = assembleToObject('// comment\nmain: jmp r14 // trailing\n');
assert.strictEqual(comments.sections[0].size, 4);
const literal = assembleToObject('main:\n  mov r1, "A"\n');
const numeric = assembleToObject('main:\n  mov r1, 65\n');
assert.strictEqual(literal.sections[0].content[0], numeric.sections[0].content[0]);
assert.strictEqual(literal.relocations.length, 0);
const prefixedNumeric = assembleToObject('main:\n  mov r1, 0x0800\n  mov r2, 0b1010\n  mov r3, external\n');
assert.deepStrictEqual(prefixedNumeric.relocations.map(relocation => relocation.symbol), ['external']);
assert.deepStrictEqual(prefixedNumeric.symbols.filter(symbol => !symbol.defined).map(symbol => symbol.name), ['external']);
const equ = assembleToObject('.equ value 7\nmain:\n  mov r1, value\n');
assert.strictEqual(equ.relocations.length, 0);
assert.strictEqual(equ.sections[0].content.length, 1);
const address = assembleToObject('main:\n  jmp r2 + target, r14\ntarget:\n  jmp r14\n');
assert.strictEqual(address.relocations[0].symbol, 'target');
assert.strictEqual(address.relocations[0].kind, 'CALL16');
assert.strictEqual(address.relocations[0].debug.column, 10);
assert.strictEqual(address.sections[0].source.includes('jmp r2 + target'), true);
assert.strictEqual(address.symbols.find(symbol => symbol.name === 'main').binding, 'local');
const exported = assembleToObject('main:\n  jmp r14\n', { exports: ['main'] });
assert.strictEqual(exported.symbols.find(symbol => symbol.name === 'main').binding, 'global');
console.log('assemble object tests passed');
